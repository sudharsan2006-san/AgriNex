/**
 * Ensures initial machinery items exist in Firestore. If the collection is empty,
 * batch-writes the curated realistic initial fleet of 15 agricultural machines.
 */
export async function seedMachineryIfEmpty(): Promise<void> {
  try {
    const snap = await getDocs(collection(db, "machinery"));
    if (!snap.empty) {
      return;
    }

    console.log("[MachinerySeed] Seeding initial machinery catalog (15 items) into Firestore...");
    const batch = writeBatch(db);

    for (const item of INITIAL_MACHINERY) {
      const docRef = doc(collection(db, "machinery"));
      batch.set(docRef, {
        ...item,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp(),
      });
    }

    await batch.commit();
    console.log("[MachinerySeed] Successfully seeded initial machinery catalog (15 items).");
  } catch (err) {
    console.warn("[MachinerySeed] Auto-seed failed or skipped:", err);
  }
}
